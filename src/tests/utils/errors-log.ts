import { expect } from "@playwright/test";
import { TRPCError } from "@trpc/server";
import { getHTTPStatusCodeFromError } from "@trpc/server/http";
import { getTableName } from "drizzle-orm";
import type { PgColumn, PgTable } from "drizzle-orm/pg-core";
import type { z } from "zod";

import { AppContextStorage, UserMode } from "@/contexts/app-context";
import { PG_UNIQUE_VIOLATION } from "@/lib/handlers";
import { LoggerLevels, LogMessages } from "@/logging/types";
import type { AppRouter } from "@/routes/api/trpc/$";
import { expectErrorsLog, type TUserConfig } from "@/tests/utils/fixtures";
import type { TProcedurePath } from "@/tests/utils/trpc";

export type TErrorCode = TRPCError["code"];
type TEvent = Record<string, unknown>;

// The user mode of the cookie the client sends, which may have none, or null without the cookie
type TClientUserConfig = Partial<TUserConfig> | null;

const ADMIN_USER_CONFIG: TClientUserConfig = { userMode: UserMode.Admin };

export function escapeRegExp(text: string) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// A message only known by its pattern is a regular expression without anchors
function errorMessage(message: string | RegExp) {
  return typeof message === "string" ? message : expect.stringMatching(new RegExp(`^${message.source}$`));
}

// A stack starts with the name and the message of its error, followed by its frames
export function errorStack(name: string, message: string | RegExp) {
  const messagePattern = typeof message === "string" ? escapeRegExp(message) : message.source;
  return expect.stringMatching(new RegExp(`^${escapeRegExp(name)}: ${messagePattern}\\n\\s+at `));
}

// The server sees the internal URL of the request, whose host is not the one of the tests
function requestUrl(pathAndQuery: string) {
  return expect.stringMatching(new RegExp(`^https?://[^/]+${escapeRegExp(pathAndQuery)}$`));
}

function clientContext(userConfig: TClientUserConfig) {
  return userConfig === null
    ? {}
    : { appContextStorage: new AppContextStorage(userConfig.userMode, userConfig.machineId).toJSON() };
}

export function httpRequestFailedEvent(method: "GET" | "POST", statusCode: number, pathAndQuery: string): TEvent {
  return {
    level: LoggerLevels.error,
    message: LogMessages.httpRequestFailed,
    method,
    statusCode,
    url: requestUrl(pathAndQuery),
  };
}

export function invalidParamsEvent(message: string, params: Record<string, string>): TEvent {
  return { level: LoggerLevels.error, message, params };
}

export function clientLogEvent(
  level: LoggerLevels,
  message: string,
  userConfig: TClientUserConfig = ADMIN_USER_CONFIG,
  meta: Record<string, unknown> = {},
): TEvent {
  return { ...clientContext(userConfig), ...meta, level, message };
}

// The error the client logs, which only keeps the message of the error it got
export function clientErrorEvent(
  clientErrorMessage: string | RegExp,
  {
    userConfig = ADMIN_USER_CONFIG,
    message = LogMessages.clientError,
  }: { userConfig?: TClientUserConfig; message?: string } = {},
): TEvent {
  return clientLogEvent(LoggerLevels.error, message, userConfig, {
    error: {
      message: errorMessage(clientErrorMessage),
      name: "Error",
      stack: errorStack("Error", clientErrorMessage),
    },
  });
}

// The message of the error of a schema that rejects the input, as both the client and the server log it
export function schemaErrorMessage(schema: z.ZodType, input: unknown) {
  const result = schema.safeParse(input);
  expect(result.success, "Wrong test set up: The schema should reject the input").toBe(false);
  return result.error!.message;
}

export function trpcError(code: TErrorCode, message: string) {
  return { code, message, name: "TRPCError", stack: errorStack("TRPCError", message) };
}

export interface TUniqueViolation {
  constraintName: string;
  table: PgTable;
  // The indexed expression and the value that is taken, as Postgres writes them
  key: string;
  value: string;
}

// Postgres quotes the identifiers that are not in lowercase
function quoteIdentifier(name: string) {
  return /^[a-z_][a-z0-9_]*$/.test(name) ? name : `"${name}"`;
}

export function uniqueColumnsViolation(
  constraintName: string,
  table: PgTable,
  columns: Array<[PgColumn, unknown]>,
): TUniqueViolation {
  return {
    constraintName,
    key: columns.map(([column]) => quoteIdentifier(column.name)).join(", "),
    table,
    value: columns.map(([, value]) => String(value)).join(", "),
  };
}

// Name constraints are unique on the trimmed lowercase name
export function uniqueNameViolation(constraintName: string, table: PgTable, name: string): TUniqueViolation {
  return { constraintName, key: "lower(name)", table, value: name.trim().toLowerCase() };
}

// The query is generated by Drizzle, so only the error of the database is checked in full
function uniqueViolationError({ constraintName, table, key, value }: TUniqueViolation) {
  const message = `duplicate key value violates unique constraint "${constraintName}"`;
  return {
    cause: {
      code: PG_UNIQUE_VIOLATION,
      constraint: constraintName,
      detail: `Key (${key})=(${value}) already exists.`,
      file: expect.any(String),
      length: expect.any(Number),
      message,
      name: "error",
      routine: expect.any(String),
      schema: "public",
      severity: "ERROR",
      stack: errorStack("error", message),
      table: getTableName(table),
    },
    message: expect.stringMatching(/^Failed query: /),
    name: "DrizzleQueryError",
    query: expect.any(String),
    stack: expect.stringMatching(/^DrizzleQueryError: Failed query: /),
  };
}

export function mutationErrorEvent(error: Record<string, unknown>): TEvent {
  return { error, level: LoggerLevels.error, message: LogMessages.mutationError };
}

// A conflict is not logged as a failed request
export function expectUniqueViolationRejected(
  uniqueViolation: TUniqueViolation,
  message: string,
  userConfig: TClientUserConfig = ADMIN_USER_CONFIG,
) {
  expectErrorsLog(mutationErrorEvent(uniqueViolationError(uniqueViolation)), clientErrorEvent(message, { userConfig }));
}

interface TRejectedMutation {
  procedurePath: TProcedurePath<AppRouter["_def"]["record"]>;
  code: TErrorCode;
  // The message the client gets
  message: string;
  userConfig?: TClientUserConfig;
  // The error the procedure logs before it is rejected, if it gets to run
  serverError?: Record<string, unknown> | null;
}

export function rejectedMutationEvents({
  procedurePath,
  code,
  message,
  userConfig = ADMIN_USER_CONFIG,
  serverError = trpcError(code, message),
}: TRejectedMutation): Array<TEvent> {
  const statusCode = getHTTPStatusCodeFromError(new TRPCError({ code }));
  return [
    ...(serverError === null ? [] : [mutationErrorEvent(serverError)]),
    httpRequestFailedEvent("POST", statusCode, `/api/trpc/${procedurePath}?batch=1`),
    clientErrorEvent(message, { userConfig }),
  ];
}

export function expectRejectedMutation(rejectedMutation: TRejectedMutation) {
  expectErrorsLog(...rejectedMutationEvents(rejectedMutation));
}
