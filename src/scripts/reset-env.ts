import { execSync } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";

import { sql } from "drizzle-orm";

import logger from "@/logging/logger";
import { MOCK_DATA_PATH } from "@/tests/mock-data";

export default async function resetEnv() {
  if (process.env.LOGS_PATH === undefined) {
    logger.crit("Environment variable LOGS_PATH is not set");
    process.exit(1);
  }

  if (process.env.BLUEPRINT_ROOT_PATH === undefined) {
    logger.crit("Environment variable BLUEPRINT_ROOT_PATH is not set");
    process.exit(1);
  }

  if (process.env.SELL_ORDER_ROOT_PATH === undefined) {
    logger.crit("Environment variable SELL_ORDER_ROOT_PATH is not set");
    process.exit(1);
  }

  if (process.env.TAGS_ROOT_PATH === undefined) {
    logger.crit("Environment variable TAGS_ROOT_PATH is not set");
    process.exit(1);
  }

  if (process.env.DELIVERY_NOTE_ROOT_PATH === undefined) {
    logger.crit("Environment variable DELIVERY_NOTE_ROOT_PATH is not set");
    process.exit(1);
  }

  if (process.env.INVOICE_ROOT_PATH === undefined) {
    logger.crit("Environment variable INVOICE_ROOT_PATH is not set");
    process.exit(1);
  }

  if (process.env.NODE_ENV === "production") {
    logger.crit("resetEnv should not be run in production");
    process.exit(1);
  }

  if (process.env.DATABASE_URL === undefined) {
    logger.crit("DATABASE_URL is not set");
    process.exit(1);
  }
  logger.info("Resetting environment", { databasePath: process.env.DATABASE_URL, env: process.env.NODE_ENV });

  const db = (await import("@/db")).default;

  // No cleanDatabase before this: its DELETEs reach Electric through replication after the tables are dropped, crashing its shape pipeline
  // Dropping the schema stops drizzle-kit from asking rename-or-create questions for new columns, which --force can't answer
  await db.execute(sql.raw("DROP SCHEMA public CASCADE; CREATE SCHEMA public;")).catch((err: unknown) => {
    logger.crit("Failed to drop the public schema", err);
    process.exit(1);
  });

  try {
    execSync("bunx drizzle-kit push --force", { stdio: "inherit" });
  } catch (err) {
    logger.crit("Failed to reset the database", err);
    process.exit(1);
  }

  await resetBlueprints();
  await resetSellOrders();
  await resetTags();
  await resetDeliveryNotes();
  await resetInvoices();

  if (process.env.DELETE_LOGS_ON_STARTUP === "true") {
    await emptyDirectory("LOGS", process.env.LOGS_PATH);
  }
}

async function resetDirectory(sourceName: string, sourcePath: string, destPath: string) {
  try {
    await fs.rm(destPath, { force: true, recursive: true });
  } catch (err) {
    logger.crit(`Failed to remove existing ${sourceName}`, err);
    process.exit(1);
  }

  return fs.cp(sourcePath, destPath, { recursive: true }).catch((err: unknown) => {
    logger.crit(`Failed to copy ${sourceName}`, err);
    process.exit(1);
  });
}

async function emptyDirectory(directoryName: string, directoryPath: string) {
  await fs.rm(directoryPath, { force: true, recursive: true }).catch((err: unknown) => {
    logger.crit(`Failed to remove existing ${directoryName}`, err);
    process.exit(1);
  });

  return fs.mkdir(directoryPath, { recursive: true }).catch((err: unknown) => {
    logger.crit(`Failed to create ${directoryName}`, err);
    process.exit(1);
  });
}

export async function resetBlueprints() {
  return resetDirectory("BLUEPRINTS", path.join(MOCK_DATA_PATH, "BLUEPRINTS"), process.env.BLUEPRINT_ROOT_PATH!);
}

export async function resetSellOrders() {
  return resetDirectory("SELL_ORDERS", path.join(MOCK_DATA_PATH, "SELL_ORDERS"), process.env.SELL_ORDER_ROOT_PATH!);
}

// Tags are only ever generated by the app, so there is no mock data to restore
export async function resetTags() {
  return emptyDirectory("TAGS", process.env.TAGS_ROOT_PATH!);
}

async function resetDeliveryNotes() {
  return emptyDirectory("DELIVERY_NOTES", process.env.DELIVERY_NOTE_ROOT_PATH!);
}

async function resetInvoices() {
  return emptyDirectory("INVOICES", process.env.INVOICE_ROOT_PATH!);
}
